_PUBLIC_ACTION = re.compile(r"\b(?:protest\w*|протест\w*|митинг\w*|skup|skupu|скуп|скупу)\b", re.I)
_TRAFFIC = r"(?:движени\w*|проезд\w*|saobra[ćc]aj\w*|саобраћај\w*)"
_LIMIT = (
    r"(?:ограничи\w*|ограничен\w*|закро\w*|закры\w*|перекро\w*|перекры\w*|"
    r"obustav\w*|zatvor\w*|ogranič\w*|обустав\w*|затвор\w*|огранич\w*)"
)
_TRAFFIC_LIMIT = re.compile(
    rf"\b{_TRAFFIC}\b[^\n.!?;]{{0,64}}\b{_LIMIT}\b"
    rf"|\b{_LIMIT}\b[^\n.!?;]{{0,64}}\b{_TRAFFIC}\b", re.I,
)
_UNCERTAIN = re.compile(
    r"\b(?:не|возможно|может|могут|možda|može|mogu|можда|може|могу|nije|ne|није)\b", re.I,
)


def unsupported_action_traffic_effect(text: str, *, quotes: Iterable[str],
                                      sources: Iterable[str]) -> bool:
    """Block a definite traffic restriction inferred from an announced public action."""
    return bool(
        _TRAFFIC_LIMIT.search(text)
        and not _UNCERTAIN.search(text)
        and any(_PUBLIC_ACTION.search(source) for source in sources)
        and not any(_TRAFFIC_LIMIT.search(quote) and not _UNCERTAIN.search(quote)
                    for quote in quotes)
    )
